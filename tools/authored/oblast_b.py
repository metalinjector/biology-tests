def _umbel_svg():
    """Простой и сложный зонтик рядом."""
    b = text(380, 24, "Зонтик: цветоножки одинаковой длины выходят из одной точки", 15, 700)

    def fan(cx, cy, length, nflow, spread, r, fill, stroke, width=1.8):
        out = ""
        ends = []
        for i in range(nflow):
            a = math.radians(-90 - spread / 2 + spread * i / (nflow - 1))
            x = cx + length * math.cos(a)
            y = cy + length * math.sin(a)
            out += f'<line x1="{cx}" y1="{cy}" x2="{x:.1f}" y2="{y:.1f}" stroke="#2f7a3b" stroke-width="{width}"/>'
            ends.append((x, y))
        for x, y in ends:
            if r:
                out += f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="1.3"/>'
        return out, ends

    # простой зонтик
    cx, top = 190, 210
    b += text(cx, 56, "Простой зонтик", 14, 700, fill=PAL["violet"][1])
    b += f'<line x1="{cx}" y1="380" x2="{cx}" y2="{top}" stroke="#2f7a3b" stroke-width="3"/>'
    fb, _ = fan(cx, top, 120, 7, 130, 10, "#f7d3e2", "#b4235f")
    b += fb
    b += f'<circle cx="{cx}" cy="{top}" r="4" fill="{INK}"/>'
    b += f'<line x1="{cx + 6}" y1="{top + 2}" x2="{cx + 70}" y2="{top + 70}" stroke="{MUTED}" stroke-width="1"/>'
    b += text(cx + 74, top + 74, "укороченная главная ось", 12.5, 400, anchor="start", fill=MUTED)
    b += text(cx, 410, "вишня, лук, первоцвет, сусак", 13, 600, fill=INK)

    # сложный зонтик
    cx2, top2 = 560, 250
    b += text(cx2, 56, "Сложный зонтик", 14, 700, fill=PAL["teal"][1])
    b += f'<line x1="{cx2}" y1="380" x2="{cx2}" y2="{top2}" stroke="#2f7a3b" stroke-width="3"/>'
    fb2, ends = fan(cx2, top2, 105, 5, 120, 0, "", "", 2.2)
    b += fb2
    for x, y in ends:
        small, _ = fan(x, y, 34, 5, 120, 5, "#fff4d6", "#8a6512", 1.2)
        b += small
    b += f'<circle cx="{cx2}" cy="{top2}" r="4" fill="{INK}"/>'
    b += text(cx2, 410, "морковь, укроп, петрушка", 13, 600, fill=INK)
    b += text(cx2, 430, "каждый луч несёт маленький зонтик (зонтичек)", 12, 400, fill=MUTED, italic=True)
    return svg(760, 445, b, "Схема соцветия зонтик")


