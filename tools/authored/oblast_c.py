def _carrot_svg():
    """Корнеплод моркови: головка, шейка, собственно корень."""
    cx, top, bot = 200, 142, 410
    b = text(380, 24, "Из чего состоит корнеплод (морковь)", 15, 700)
    # листья розетки
    for dx, h in ((-34, 70), (-16, 88), (0, 96), (18, 86), (36, 66)):
        b += f'<path d="M{cx + dx * 0.3:.1f},{top} C{cx + dx * 0.6:.1f},{top - h * 0.5:.1f} {cx + dx:.1f},{top - h * 0.8:.1f} {cx + dx * 1.3:.1f},{top - h:.1f}" fill="none" stroke="#2f7a3b" stroke-width="3" stroke-linecap="round"/>'
    pts_l, pts_r = [], []
    for i in range(29):
        y = top + (bot - top) * i / 28
        t = (y - top) / (bot - top)
        hw = 46 * (1 - t ** 1.6) + 2
        pts_l.append((cx - hw, y))
        pts_r.append((cx + hw, y))
    d = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts_l) + " L" + " L".join(f"{x:.1f},{y:.1f}" for x, y in reversed(pts_r)) + " Z"
    b += f'<path d="{d}" fill="#fbc58f" stroke="#c2410c" stroke-width="1.6"/>'
    # боковые корни
    for y, side in ((255, -1), (282, 1), (310, -1), (336, 1), (362, -1)):
        t = (y - top) / (bot - top)
        hw = 46 * (1 - t ** 1.6) + 2
        x0 = cx + side * hw
        b += f'<path d="M{x0:.1f},{y} q{side * 16},4 {side * 28},16" fill="none" stroke="#c2410c" stroke-width="1.2"/>'
    # рубцы листьев на головке
    for dx in (-22, -6, 10, 26):
        b += f'<path d="M{cx + dx - 5},{top + 12} q5,-5 10,0" fill="none" stroke="#8a6512" stroke-width="1.3"/>'
    # границы зон
    for y in (top + 28, top + 70):
        b += f'<line x1="{cx - 70}" y1="{y}" x2="{cx + 70}" y2="{y}" stroke="{MUTED}" stroke-width="1" stroke-dasharray="5 4"/>'
    zones = [
        ("Головка", "укороченный стебель: листья и почки", top + 14, 145, "green"),
        ("Шейка", "подсемядольное колено: нет ни листьев, ни корней", top + 49, 218, "gold"),
        ("Собственно корень", "утолщённый главный корень с боковыми корнями", top + 160, 300, "orange"),
    ]
    for name, sub, py, ly, col in zones:
        stroke = PAL[col][1]
        b += f'<line x1="{cx + 30}" y1="{py}" x2="372" y2="{ly}" stroke="{MUTED}" stroke-width="1"/>'
        b += f'<circle cx="{cx + 30}" cy="{py}" r="3" fill="{stroke}"/>'
        b += text(380, ly + 2, name, 15, 700, anchor="start", fill=stroke)
        b += text(380, ly + 20, sub, 12.5, 400, anchor="start", fill=MUTED)
    b += text(380, 382, "Запасающая ткань — паренхима", 13, 600, anchor="start", fill=INK)
    b += text(380, 400, "(сахара, крахмал, каротин у моркови)", 12.5, 400, anchor="start", fill=MUTED)
    return svg(760, 425, b, "Строение корнеплода моркови")


def _leg_svg():
    """Ходильная нога насекомого: пять отделов от тела к концу."""
    b = text(380, 24, "Нога насекомого: от тела к кончику", 15, 700)
    b += '<ellipse cx="70" cy="130" rx="58" ry="38" fill="#eef1f0" stroke="#5b6b66" stroke-width="1.6"/>'
    b += text(70, 135, "грудь", 13, 600, fill=MUTED)
    segs = [
        ("тазик", "2", (118, 140), (168, 166), 16, "violet"),
        ("вертлуг", "3", (168, 166), (198, 172), 11, "teal"),
        ("бедро", "1", (198, 172), (390, 110), 15, "blue"),
        ("голень", "5", (390, 110), (565, 232), 9, "green"),
    ]
    for name, num, (x1, y1), (x2, y2), wdt, col in segs:
        fill, stroke = PAL[col]
        b += f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{stroke}" stroke-width="{wdt + 3}" stroke-linecap="round"/>'
        b += f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{fill}" stroke-width="{wdt}" stroke-linecap="round"/>'
    # лапка — пять члеников и коготки
    x, y = 565, 232
    for i in range(5):
        x2, y2 = x + 26, y + 6
        b += f'<line x1="{x}" y1="{y}" x2="{x2}" y2="{y2}" stroke="#c2410c" stroke-width="9" stroke-linecap="round"/>'
        b += f'<line x1="{x}" y1="{y}" x2="{x2}" y2="{y2}" stroke="#fdeee2" stroke-width="6" stroke-linecap="round"/>'
        x, y = x2 + 2, y2
    b += f'<path d="M{x},{y} q12,-2 14,10 M{x},{y} q14,4 10,16" fill="none" stroke="#c2410c" stroke-width="2"/>'
    labels = [("тазик", "2", 140, 205, "violet"), ("вертлуг", "3", 190, 225, "teal"), ("бедро", "1", 300, 104, "blue"),
              ("голень", "5", 470, 140, "green"), ("лапка", "4", 640, 290, "orange")]
    for name, num, lx, ly, col in labels:
        stroke = PAL[col][1]
        b += f'<circle cx="{lx - 14}" cy="{ly - 5}" r="12" fill="#fff" stroke="{stroke}" stroke-width="1.6"/>'
        b += text(lx - 14, ly, num, 13, 700, fill=stroke)
        b += text(lx + 4, ly, name, 14, 700, anchor="start", fill=stroke)
    b += text(380, 330, "Порядок от тела: тазик (2) → вертлуг (3) → бедро (1) → голень (5) → лапка (4)", 14, 700)
    return svg(760, 345, b, "Отделы ноги насекомого")


